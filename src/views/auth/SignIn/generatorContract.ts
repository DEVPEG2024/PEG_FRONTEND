/** Téléchargement du contrat en .txt, pour que le Générateur en garde une copie. */
export function downloadGeneratorContract(): void {
  const blob = new Blob([GENERATOR_CONTRACT_TEXT], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `Contrat-Generateur-PEG-v${GENERATOR_CONTRACT_VERSION}.txt`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
